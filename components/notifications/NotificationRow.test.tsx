import { fireEvent, render, screen } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { describe, expect, it, vi } from "vitest";

import type { AppNotification } from "@/types";

import { NotificationRow } from "./NotificationRow";

const notification: AppNotification = {
  id: "event-1",
  escrowId: "order-1",
  escrowItem: "Camera",
  type: "FUNDED",
  message: "Payment received",
  timestamp: "2026-01-01T00:00:00Z",
  read: false,
};

describe("NotificationRow activation", () => {
  it("marks read once through the native click generated by Enter", async () => {
    const user = userEvent.setup();
    const onRead = vi.fn();
    render(<NotificationRow n={notification} onRead={onRead} />);
    const link = screen.getByRole("link");
    link.focus();

    await user.keyboard("{Enter}");

    expect(link).toHaveAttribute("href", "/track/order-1");
    expect(onRead).toHaveBeenCalledExactlyOnceWith(notification.id);
  });

  it("marks read once on pointer activation", async () => {
    const user = userEvent.setup();
    const onRead = vi.fn();
    render(<NotificationRow n={notification} onRead={onRead} />);

    await user.click(screen.getByRole("link"));

    expect(onRead).toHaveBeenCalledExactlyOnceWith(notification.id);
  });

  it.each([
    { key: "Enter" },
    { key: "Enter", ctrlKey: true },
    { key: "Enter", metaKey: true },
    { key: "Enter", shiftKey: true },
    { key: " " },
  ])("does not cancel or mutate read state for keydown %j", (init) => {
    const onRead = vi.fn();
    render(<NotificationRow n={notification} onRead={onRead} />);
    const event = new KeyboardEvent("keydown", { ...init, bubbles: true, cancelable: true });

    fireEvent(screen.getByRole("link"), event);

    expect(event.defaultPrevented).toBe(false);
    expect(onRead).not.toHaveBeenCalled();
  });

  it("leaves Space to native scrolling without marking the link read", async () => {
    const user = userEvent.setup();
    const onRead = vi.fn();
    render(<NotificationRow n={notification} onRead={onRead} />);
    screen.getByRole("link").focus();

    await user.keyboard(" ");

    expect(onRead).not.toHaveBeenCalled();
  });

  it.each([{ ctrlKey: true }, { metaKey: true }, { shiftKey: true }])(
    "preserves modified click activation %j",
    (modifiers) => {
      const onRead = vi.fn();
      render(<NotificationRow n={notification} onRead={onRead} />);
      const event = new MouseEvent("click", { ...modifiers, bubbles: true, cancelable: true });

      fireEvent(screen.getByRole("link"), event);

      expect(event.defaultPrevented).toBe(false);
      expect(onRead).toHaveBeenCalledExactlyOnceWith(notification.id);
    }
  );
});
